          <h1 class="page-title">Complaints Against AIMS, Its Board, or Committees</h1>
          <hr>
          <h2 id="introduction" class="section-title">General Preamble</h2>
          <p>
              AIMS views complaints as an opportunity to learn, improve, and resolve issues for those who raise
              concerns. Complaints also help us strengthen our practices and services in the future. <br>
              Our approach is to: <br>
              Provide a fair, clear, and accessible complaints procedure for anyone wishing to raise a concern.
              Publicise the complaints procedure so people know how to contact AIMS. <br>
              Ensure all staff and volunteers understand their responsibilities when a complaint is received.
              Investigate all complaints impartially and promptly. <br>Resolve complaints wherever possible, restoring
              relationships where appropriate. <br>
              Gather insights from complaints to improve AIMS’ policies and practices. <br>
              Definition of a Complaint <br>A complaint is any expression of dissatisfaction about AIMS, its services,
              procedures, or conduct,
              whether the concern is justified or not, that falls short of expected standards. <br>Sources of Complaints
              <br>Complaints may be raised by: <br>
          </p>
          <ul>
              <li>Clients or service users,</li>
              <li>Members or registrants,</li>
              <li>Donors or supporters,</li>
              <li>Community members with a legitimate interest in AIMS’ work.</li>
          </ul>
          <p>
              Complaints may initially be received verbally, e.g., by phone, but must ultimately be submitted in writing
              or by email. <br>
              Note: This policy does not cover complaints from AIMS staff, who should follow the organisation’s
              separate Discipline and Grievance Policies.
          </p>

          <p> <strong>Confidentiality</strong></p>
          <p>All complaint information will be handled sensitively and shared only with those who need to know. AIMS
              will comply with all relevant data protection laws.</p>

          <p> <strong>Responsibility</strong></p>
          <p>Overall responsibility for this policy and its implementation rests with the AIMS Board, through the Chair
              of the Board.</p>
          <p><strong>Review</strong></p>
          <p>This policy will be reviewed regularly and updated as required to reflect best practice.</p>
          <p>Adopted: June 2025</p>
          <p>Complaints should be emailed to: <a href="mailto:info@aimsonline.org">info@aimsonline.org</a></p>
