        <h1 class="page-title">Complaints Procedure</h1>
        <hr>

        <h2 id="introduction" class="section-title">Introduction</h2>
        <p>
            This document sets out the Association of Islamic Mental Health Specialists’ (AIMS) policy on how
            sanctions may be applied by its Disciplinary Panels in cases concerning fitness to practise. <br>
            Decisions about whether sanctions are necessary, and if so, which sanctions are appropriate, rest solely
            with the Panel that hears the case. The Panel operates independently from the AIMS Board to ensure
            impartiality. This policy provides guidance only; it does not prescribe fixed sanctions. Each case must be
            assessed individually, on its own merits. <br>The purpose of this guidance is to support Panels in making
            fair, consistent, proportionate, and
            transparent decisions.
        </p>
        <div>
            <h3 id="procedure-introduction" class="subsection-title">1. Purpose of Sanctions</h3>
            <div>
                <p><strong>1.1</strong> The primary purpose of disciplinary and fitness-to-practise proceedings is to
                    protect
                    the public, not to
                    punish members. Sanctions may sometimes feel punitive in effect, but they should only ever be
                    imposed
                    for the purposes of safeguarding and upholding professional standards.
                </p>
            </div>
            <div>
                <p><strong>1.2 </strong> A Panel’s role is to: <br>
                <ul>
                    <li>consider a registrant’s actions,</li>
                    <li>decide whether their fitness to practise falls below expected professional standards, and</li>
                    <li>assess whether they may pose a risk to service users in the future.</li>
                    <li>Where a risk is identified, the Panel must determine what level of intervention is required to
                        protect
                        the
                        public.</li>
                </ul>
                </p>
            </div>
            <div>
                <p><strong>1.3</strong> Sanctions may only be applied in relation to facts that are either admitted by
                    the
                    registrant or proven
                    by the Panel. They must also take account of all relevant circumstances contributing to the finding
                    of
                    impairment.
                </p>
            </div>
            <div>
                <p><strong>1.4</strong> While public safety is the primary concern, Panels must also consider wider
                    public
                    interests,
                    including:
                </p>
                <ul>
                    <li>deterring other registrants from similar conduct,</li>
                    <li>maintaining trust in the counselling and mental health profession, and</li>
                    <li>protecting confidence in AIMS as a regulatory body.</li>
                </ul>
            </div>
            <div>
                <p><strong>1.5</strong> Available sanctions may include, but are not limited to:
                </p>
                <ul>
                    <li>mediation,</li>
                    <li>a written apology,</li>
                    <li>a caution or formal warning,</li>
                    <li>removal from a role, office, or position within AIMS,</li>
                    <li>a reflective account or learning report,</li>
                    <li>additional training, supervision, or therapy,</li>
                    <li>conditions of practice,</li>
                    <li>suspension from the Register,</li>
                    <li>permanent removal from registration and membership.</li>
                </ul>
            </div>
            <div>
                <p><strong>1.6</strong> Even where impairment is established, it may sometimes be proportionate for a
                    Panel
                    not to impose
                    a sanction—for example, where the registrant has already shown insight, taken remedial action, and
                    presents no risk of repetition.
                </p>
            </div>
        </div>
        <div>
            <h3 id="bringing-complaint" class="subsection-title">2. Proportionality</h3>
            <p><strong>2.1</strong> When deciding whether to impose a sanction, and what sanction is appropriate, Panels
                should apply
                the principle of proportionality. This means balancing the protection of the public and wider interests
                with
                fairness to the registrant. <br>Panels should ask <br>Is the sanction within the Panel’s authority?
                <br>Is it suitable to achieve the necessary level of public protection? <br> Does it take account of
                wider public interest considerations, such as confidence in the profession? <br> Is it the least
                restrictive option available to achieve the required level of protection? <br>Does it strike the right
                balance between public safety and the rights of the registrant?
            </p>
        </div>


        <div>
            <h3 id="complaints-process" class="subsection-title">3. Insight and Remorse</h3>

            <div>
                <p> <strong>3.1</strong>AIMS is committed to fairness, equality, and respect for diversity. Panels must
                    conduct all
                    proceedings without bias or discrimination.</p>
            </div>
            <div>
                <p><strong>3.2</strong> The goal of fitness-to-practise proceedings is to ensure safety and public
                    protection—not
                    punishment. An important factor in decision-making will often be the extent to which a registrant
                    demonstrates insight into their actions and a willingness to address shortcomings.
            </div>
            <div>
                <p><strong>3.3</strong> Panels should take account of cultural and linguistic differences in how
                    remorse, apology, or
                    responsibility are expressed—whether verbally, in writing, or through conduct.
                </p>
            </div>
            <div>
                <p><strong>3.4</strong> Key questions for Panels include:</p>
                <ul>
                    <li>Has the registrant genuinely recognised their failings?</li>
                    <li>Have they taken, or are they taking, appropriate steps to remedy them?</li>
                    <li>Is there a risk of the behaviour being repeated?</li>
                </ul>
                <p>The focus should be on the evidence of genuine change rather than the particular words or style of
                    expression.</p>
            </div>
            <div>
                <p><strong>3.5</strong> Registrants are expected to act with honesty and openness towards clients.
                    Panels should generally
                    view genuine explanations, empathy, or apologies as positive indicators. These should not normally
                    be
                    taken as admissions of liability unless there is clear evidence to the contrary.
                </p>
            </div>
        </div>
        <div>
            <h3 id="formal-procedure" class="subsection-title">4. Procedure</h3>

            <div>
                <p> <strong>4.1</strong> The availability of sanctions must never influence a Panel’s decision on
                    whether a registrant’s fitness
                    to practise is impaired. The decision on impairment and the decision on sanction are separate stages
                    and must be treated as such.</p>
            </div>
            <div>
                <p><strong>4.2</strong> To emphasise this separation, Panels should first retire to decide whether
                    fitness to practise is
                    impaired. Once a decision is reached, the Panel should return to announce its findings and give
                    clear
                    reasons. <br>
                    If impairment is established, the Panel will then hear submissions from both parties regarding
                    mitigating
                    or aggravating factors. After considering these, the Panel will again retire to decide, in ascending
                    order,
                    what sanction (if any) is appropriate. The Panel will then return to announce the sanction and
                    provide
                    reasons for their decision.
                </p>
            </div>
            <div>
                <p><strong>4.3</strong> Panels must ensure that registrants fully understand any sanction being imposed.
                    The Panel Chair
                    should clearly explain:
                </p>
                <ul>
                    <li>what sanction is being applied,</li>
                    <li>the reasons for imposing it, and</li>
                    <li>the practical implications for the registrant.</li>
                </ul>
                <p>Explanations must be direct and unambiguous. The purpose is to communicate the decision, not to
                    lecture or moralise.</p>
            </div>
        </div>

        <div>
            <h3 id="disciplinary-measures" class="subsection-title">5. Sanctions</h3>
            5
            <div>
                <p><strong>5.2</strong> A registrant may be required to issue a formal apology to the complainant,
                    particularly when mistakes
                    have been acknowledged and an apology is appropriate for resolution.</p>
            </div>
            <div>
                <p><strong>5.3</strong>The registrant may receive a formal warning letter relating to their conduct or
                    judgement. This is a
                    cautionary measure but not a restriction on practice.</p>
            </div>
            <div>
                <p><strong>5.4</strong> If the registrant holds an office, committee membership, or training role within
                    AIMS, they may be
                    removed from that position.</p>
            </div>
            <div>
                <p><strong>5.5</strong> The registrant may be required to submit a written account explaining what they
                    have learned from the
                    incident and how they plan to prevent similar issues in the future.</p>
            </div>
            <div>
                <p><strong>5.6</strong> The Panel may require the registrant to undertake specific training, additional
                    professional supervision, or
                    therapeutic support for a minimum duration, with the aim of strengthening competence and
                    safeguarding
                    service users.</p>
            </div>
            <div>
                <p><strong>5.7</strong> A caution may be appropriate in cases that are more serious than those requiring
                    only a warning, but
                    where suspension or conditions would be disproportionate. This is suitable for isolated lapses,
                    where the
                    registrant has shown insight, taken corrective action, and presents a low risk of recurrence.
                    <br>Cautions are time-limited, typically lasting between one and five years. <br>A three-year
                    caution is considered standard, though Panels may adjust the duration based on
                    circumstances. <br>A caution does not restrict practice but will be recorded on the public Register
                    and considered in any
                    future proceedings.
                </p>
            </div>
            <div>
                <p><strong>5.8</strong> Conditions of practice may be imposed for a fixed period of up to three years.
                    They appear on the
                    Register and may restrict certain activities, require remedial action, or both. <br> Conditions are
                    most appropriate where:</p>
                <ul>
                    <li>failings are remediable,</li>
                    <li>the registrant can continue to practise safely if monitored, and</li>
                    <li>the Panel is confident the registrant will comply.</li>
                </ul>
                <p>Conditions may include:</p>
                <ul>
                    <li>specific training or education,</li>
                    <li>enhanced supervision,</li>
                    <li>conditions of practice</li>
                    <li>restrictions on the type of work undertaken, or requirements to submit evidence of compliance.
                    </li>
                </ul>
                <p>Conditions must be realistic, proportionate, and verifiable. Another Panel should be able to assess
                    compliance at review.Conditions are unlikely to be appropriate where there is: serious
                    misconduct,dishonesty, exploitation, or abuse of clients,persistent failings, orlack of insight or
                    willingness to comply. In such cases, suspension or removal may be more suitable. <br>Panels may
                    also specify a minimum period (up to two years) before the registrant can apply to vary or lift
                    conditions, though this should only be applied where early review would be inappropriate.</p>
            </div>
            <div>
                <p><strong>5.9</strong> A suspension removes the registrant from practice for a set period of up to one
                    year. During suspension,
                    the registrant is prohibited from working in any counselling capacity, and the public Register will
                    reflect
                    this status. Suspension should be considered where:</p>
                <p>
                    a caution or conditions of practice would be insufficient to protect service users, <br> the concern
                    is serious but there is a realistic prospect that the registrant can return to safe practice, or
                    a period away from practice is needed to allow the registrant to address underlying issues.
                    <br>Suspension may be appropriate, for example, where a registrant is engaged in treatment for
                    substance
                    dependency or another condition which temporarily prevents safe practice. A time-limited suspension
                    in
                    such cases may provide space for recovery, after which conditions of practice could support a safe
                    return. <br>Panels should recognise that suspension can have significant consequences for the
                    registrant, such as
                    loss of employment. However, where lesser sanctions would not provide adequate protection, maintain
                    public confidence, or act as a sufficient deterrent, suspension may be necessary. <br>Suspension
                    cannot include additional conditions, but Panels may provide clear guidance on what steps
                    the registrant is expected to take during the suspension, so that any review panel can assess
                    progress. <br>Panels may also set a minimum period (up to 10 months) before the registrant may apply
                    for review, but
                    this should only be done where early review would not serve any purpose.
                </p>
            </div>
            <div>
                <p><strong>5.10</strong>Removal is the most serious sanction. It permanently takes a registrant off the
                    Register and terminates
                    their membership with AIMS, preventing them from practising in the profession. <br> This sanction is
                    used only in the most severe cases, particularly where there has been: <br> deliberate or reckless
                    abuse of trust (such as sexual misconduct, exploitation, or dishonesty) <br>persistent failings
                    despite previous sanctions, or <br>refusal or inability to recognise and address risks to public
                    safety.</p>

                <p>Removal may also be appropriate where the gravity of the misconduct is such that anything less would
                    fail to deter others or would undermine public confidence in the profession and in AIMS’ regulatory
                    role.
                    In cases relating to competence or health, removal should not normally be applied unless the
                    registrant
                    has already been under suspension or conditions of practice for at least two years, and there is no
                    evidence of progress.A person removed from the Register cannot apply for restoration for at least
                    five years, and only if they
                    can show compelling evidence that the concerns leading to removal have been fully resolved.</p>
            </div>
            <div>
                <p><strong>5.11</strong> Where a Panel decides on removal, suspension, or conditions of practice, it
                    also has discretion to impose
                    an interim sanction. This ensures public protection during the appeal period or while an appeal is
                    ongoing. <br>An interim sanction should not be applied automatically but only where necessary, for
                    example: <br>where there is an immediate and ongoing risk to service users or the public, or
                    where the allegations are so serious that public confidence would be undermined if the registrant
                    continued to practise unrestricted.
                    Before imposing an interim sanction, the Panel must allow both parties the opportunity to make
                    submissions.</p>
            </div>
            <div>
                <p><strong>5.12</strong> Sanctions are normally applied one at a time. Panels may impose, review, vary,
                    replace, or revoke a
                    single sanction but cannot layer multiple sanctions together in the same case. <br>A registrant will
                    only face more than one sanction at the same time in rare circumstances, such as when
                    separate complaints are brought forward. Even then, Panels should be cautious and clear in
                    explaining
                    how each sanction applies, including its duration and effect. <br>In most cases, escalation to a
                    more serious sanction is preferable to applying two at once. For example: <br>if a registrant under
                    conditions of practice breaches those conditions, the Panel is more likely to move to
                    suspension rather than adding a second sanction. <br>a suspension automatically overrides conditions
                    of practice. <br>The only time multiple sanctions may be appropriate is when unrelated and separate
                    allegations are
                    being considered. For instance, if a registrant is already subject to conditions of practice for
                    competence
                    issues and later receives a caution for unrelated misconduct, the Panel must clearly explain how the
                    caution co-exists without affecting the conditions.</p>
            </div>
        </div>

        <div>
            <h3 id="appeals" class="subsection-title">6. Publication Timescales for Sanctions</h3>
            <p>AIMS is committed to transparency in order to protect the public and maintain confidence in the
                profession. Publication of sanctions on the AIMS Register and membership list will follow these
                principles:</p>
            <div>
                <p><strong>6.1</strong> Not published if accepted and resolved. <br>Registrant may continue practice if
                    deemed safe during this process.</p>
            </div>
            <div>
                <p><strong>6.2</strong> Recorded on the Register for 1–5 years (benchmark: 3 years). <br>Does not
                    restrict practice unless otherwise stated.</p>
            </div>
            <div>
                <p><strong>6.3</strong> Can last 1–3 years (guide: 2 years). <br>Registrant may request review for
                    variation, replacement, or revocation after 2 years. <br>Practice may continue but only under
                    specified conditions.</p>
            </div>
            <div>
                <p><strong>6.4</strong> Cannot exceed 1 year. <br>Registrant cannot practise during this time.
                    <br>Suspension status is publicly noted on the Register.
                </p>
            </div>
            <div>
                <p><strong>6.5</strong> Permanent unless compelling new evidence allows application for restoration
                    after 5 years.
                    Registrant immediately loses membership and may not practise.
                    Removal is published on the Register throughout the entire period.
                </p>
            </div>
            <div>
                <p><strong>6.6</strong> May be imposed while an appeal is pending or within the appeal window.
                    Publication will specify terms, duration, and whether the registrant may continue any form of
                    practice.
                    Decided only after consultation with the parties.
                </p>
            </div>
            <div>
                <p><strong>6.6</strong> Normally only one sanction applies at a time.
                    In rare cases where multiple sanctions are appropriate, publication and duration will be clearly set
                    out by
                    the Panel.
                </p>
            </div>
        </div>
        <p><strong>📌 These measures ensure that AIMS balances fairness to members with its duty to protect service
                users and maintain public trust. Register here implies AIMS independent register and
                membership.</strong></p>

