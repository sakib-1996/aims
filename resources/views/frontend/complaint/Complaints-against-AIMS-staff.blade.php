          <h1 class="page-title">Complaints Against AIMS Staff</h1>
          <hr>
          <h2 id="introduction" class="section-title">General Preamble</h2>
          <p>
              AIMS views complaints as an opportunity to improve services, resolve issues fairly, and restore
              relationships where possible. Complaints also provide important learning for the organisation. <br>
              Our approach is to: <br>
          </p>
          <ul>
              <li>Provide a clear, fair, and accessible complaints procedure for anyone wishing to raise a concern.,
              </li>
              <li>Publicise the complaints procedure so people know how to contact AIMS,</li>
              <li>DoEnsure all staff understand their responsibilities when a complaint is received,</li>
              <li>Investigate all complaints impartially and in a timely manner.</li>
              <li>Resolve complaints wherever possible and seek to restore relationships.</li>
              <li>Gather insights from complaints to improve AIMS’ practices.</li>
          </ul>
          <p>
              Definition of a Complaint <br>
              A complaint is any expression of dissatisfaction, whether justified or not, regarding the actions,
              decisions,
              or conduct of AIMS staff or any aspect of AIMS’ operations. <br>
              Sources of Complaint
              <br>Complaints may be raised by:
          </p>
          <ul>
              <li>Clients, service users, or registrants,</li>
              <li>Members, donors, or supporters,</li>
              <li>Members of the wider community with a legitimate interest in AIMS.</li>
              <li>Complaints may be received verbally, by phone, by email, or in writing.</li>
          </ul>
          <div class="alert alert-primary" role="alert">
              Note: This policy does not cover complaints from staff, who should follow the AIMS Employee Handbook
              and relevant HR policies.
          </div>

          <p> <strong>Confidentiality</strong></p>
          <p>All complaints will be handled sensitively and shared only with those who need to know. AIMS will comply
              with all relevant data protection laws.</p>

          <p> <strong>Responsibility</strong></p>
          <p>Overall responsibility for this policy and its implementation lies with the AIMS Board, through the Chair
              of
              the Board.</p>
          <p><strong>Review</strong></p>
          <p>This policy is reviewed regularly and updated as required.</p>
          <p>Adopted: June 2025</p>
          <p>Complaints should be emailed to: <a href="mailto:info@aimsonline.org">info@aimsonline.org</a></p>
          <p>Complaints Procedure Regarding Staff <br>
              <small>Stage One – Initial Handling</small>
          </p>
          <p>In many cases, complaints are best resolved directly with the staff member involved, if appropriate.
              <br>When a complaint is received, the staff member should attempt resolution where possible.
              <br>Whether resolved or not, the complaint must be forwarded to the Chair within one week.
              <br>The Chair logs the complaint and assigns an investigator to review the matter and take appropriate
              action.
              <br>If the complaint relates to a specific staff member, they must be informed and given a fair
              opportunity to
              respond. <br>Complaints should be acknowledged within one week, including the contact details of the
              investigator
              and an expected response timeframe. <br>A full response should ideally be provided within four weeks.
              <br>If a full response is delayed, a progress update must be sent with an expected timeline. <br>All
              responses should detail the investigation process, conclusions, and any actions taken, regardless of
              whether the complaint is upheld. <br>Stage Two – Board Review <br>If the complainant is not satisfied with
              Stage One, they may request a Board-level review, handled by the
              Deputy Chair. <br>The request must be acknowledged within one week, including details of who will manage
              the review and
              the expected timeframe for a response. <br>The Deputy Chair may review the case personally or delegate a
              senior, impartial staff member to
              investigate further. <br>This may include reviewing the original documentation and speaking with both the
              Stage One
              investigator and the staff member concerned. <br>Staff involved must be informed and given an opportunity
              to respond. <br>The complainant should receive a definitive response ideally within four weeks. <br>If a
              full response is delayed, a progress update must be provided. <br>The response must describe the
              investigation, conclusions, and any action taken. <br>The decision at this stage is final. <br>Variation
              of the Procedure
          </p>
          <p>The Board may modify the procedure to avoid conflicts of interest or ensure fairness. For example, a
              complaint involving the Chair or CEO will not be led by the Chair/CEO at any stage. <br> <br>
              Monitoring and Learning</p>
          <p>Complaints are reviewed annually to identify trends, inform policy updates, and improve organisational
              practices.</p>
