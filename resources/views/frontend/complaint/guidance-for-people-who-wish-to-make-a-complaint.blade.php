          <h1 class="page-title">Complaints Procedure</h1>
          <hr>
          <h2 id="introduction" class="section-title">Introduction</h2>
          <p>
              If you wish to make a complaint against one of our registrants or affiliated counselling
              organisations, the
              following guidance will help you understand the process.
              The Association of Islamic Mental Health Specialists (AIMS) takes all complaints seriously.
              We aim to
              make the process fair, impartial, and as clear as possible for clients, organisations, and
              practitioners.
          </p>
          <h2 id="steps" class=""></h2>
          <div class="step-card">
              <h3 class="subsection-title"><span class="step-number">1</span>1. Local Resolution First
              </h3>
              <p>If you believe there is an issue, we encourage you to first raise the concern directly
                  with the counsellor or
                  their agency, using the complaints procedure usually explained at the start of
                  counselling.</p>
          </div>

          <div class="step-card">
              <h3 class="subsection-title"><span class="step-number">2</span>Submitting a Complaint to
                  AIMS</h3>
              <p>If local resolution is not successful, you may submit a formal complaint to AIMS. This
                  can be done by
                  phone, email, or in writing. Complaint forms can be requested from the AIMS office or
                  downloaded from
                  our website. If you would like to talk to someone before completing the form, please
                  email
                  us at:
                  <a href="mailto:info@aimsonline.org">info@aimsonline.org</a>
              </p>
          </div>

          <div class="step-card">
              <h3 class="subsection-title"><span class="step-number">3</span>Completing the Complaint
                  Form
              </h3>
              <p>You will need to clearly explain what you believe the counsellor or organisation did or
                  failed to do, in
                  relation to the AIMS Code of Ethics and Practice.</p>
              <p>We recognise that complaints can feel daunting or distressing. To support you, AIMS may
                  provide
                  someone to help you understand which areas of the Code may apply. This support is
                  impartial and does
                  not mean that your complaint is agreed with—it is simply to help you present your case
                  clearly.</p>
              <p>Please note: AIMS cannot provide legal advice or cover any costs (e.g. travel,
                  representation, or other
                  expenses) for either the complainant or the respondent.</p>
          </div>

          <div class="step-card">
              <h3 class="subsection-title"><span class="step-number">4</span>What Happens After You
                  Submit a Complaint
              </h3>
              <p>Please be aware that AIMS cannot provide legal advice or reimburse any costs, including
                  travel or associated expenses, for either the complainant or the practitioner.</p>


              <ul>
                  <li><strong>A. Acknowledgement:</strong> Once your complaint is formally received, the
                      Chair of AIMS will review it. You will receive an
                      acknowledgement within 7 working days, and the process of investigation will begin.
                  </li>
                  <li><strong>B. Notification to the Respondent:</strong> Within 14 working days, the
                      Chair will also write to the person or organisation complained against, setting
                      out the details of the complaint (excluding your personal contact details).
                  </li>
                  <li><strong>C. Appointment of an Investigator:</strong> AIMS will appoint an independent
                      investigator and inform you who this is. The investigator will contact
                      you to request further information or supporting evidence. You are expected to
                      cooperate with this stage
                      by answering questions and supplying any documents requested.
                      <br>
                      The investigator will then prepare a report of findings, recommending whether or not
                      there is a case to
                      answer.
                  </li>
                  <li><strong>D. Pre-hearing Assessment:</strong> The investigator’s report will be
                      presented to a Pre-hearing Assessment Panel, which will decide whether
                      the case should proceed to a Disciplinary Panel. You will be informed of this
                      decision. <br> If you disagree with a decision not to proceed, you may appeal by
                      providing further information or
                      grounds. If no sufficient grounds are found, the matter will be closed.
                  </li>
                  <li><strong>E. Disciplinary Panel:</strong> If a Disciplinary Panel is convened, both
                      parties will be invited to attend, and the evidence gathered will
                      usually be made available to both sides. The Panel will examine the case, reach a
                      conclusion, and notify
                      both parties of its decision. There will also be a right of appeal.
                  </li>
                  <li><strong>F. Sanctions:</strong> If the complaint is upheld, AIMS will impose
                      appropriate sanctions, which may include warnings,
                      conditions, suspension, or removal from the Register. The member or organisation
                      will be required to
                      comply fully with these sanctions.
                  </li>
                  <li><strong>G. Learning Outcomes:</strong> In some cases, even where the complaint is
                      not upheld, the Panel may make recommendations to
                      improve practice and ensure future safety. Learning points from cases may also be
                      shared anonymously
                      with members to strengthen best practice across the profession.</li>
              </ul>

          </div>
