                            <h5 class="mt-5 mb-3 fw-bold">6. APPEALS</h5>
                            <ul>
                                <li><strong>6.1</strong>
                                    Either party to a complaint may appeal against the decisions or sanctions of the
                                    Disciplinary Panel by
                                    writing to the Chair of the Association of Islamic Mental Health Specialists (AIMS)
                                    within
                                    two weeks of
                                    being notified of the decision. The appeal must clearly state the grounds on which it is
                                    being made.
                                </li>

                                <li><strong>6.2</strong>
                                    An appeal will not be granted if, after review, the Chair considers that:
                                    <ul class="ms-4">
                                        <li>there is insufficient evidence available, or likely to become available, to
                                            support the grounds for appeal;
                                            or</li>
                                        <li>the appeal is frivolous or vexatious.</li>
                                        <li>This decision will be final.</li>
                                    </ul>
                                </li>
                                <li><strong>6.3</strong>
                                    An appeal may be considered on any of the following grounds:
                                    <ul class="ms-4">
                                        <li>the decision was made against the weight of the evidence;</li>
                                        <li>the sanction applied is disproportionate to the findings of the Panel;</li>
                                        <li>a procedural error or impropriety may have had a material effect on the Panel’s
                                            decision;</li>
                                        <li>new evidence has become available that was not reasonably accessible at the time
                                            of the Disciplinary
                                            Panel hearing.</li>
                                    </ul>
                                </li>
                                <li><strong>6.4</strong>
                                    If an appeal is accepted, the Chair will appoint an Appeals Panel consisting of four
                                    suitably
                                    experienced individuals, including at least one lay member. The Appeals Panel will be
                                    convened
                                    specifically for this purpose, and its members will not be part of the AIMS Board,
                                    Executive, or any
                                    committee with prior involvement in the case
                                </li>
                                <li><strong>6.5</strong>
                                    The Appeals Panel will consider the appeal in full, which may include a hearing where
                                    parties are
                                    given the opportunity to attend and present their case. The Panel may also seek legal or
                                    professional
                                    advice if required. Following its deliberations, the Chair will write to both parties to
                                    notify them of the
                                    outcome and whether the appeal has been upheld or rejected
                                </li>
                                <li><strong>6.6</strong>
                                    The decision of the Appeals Panel is final. No further appeal will be available within
                                    the Association.
                                </li>

